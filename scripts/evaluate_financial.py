"""Evaluate the bundled checkpoint and fusion on independent synthetic splits."""

import argparse
from hashlib import sha256
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "services/graph-detector"))

from evaluation.dataset import generate_split
from evaluation.metrics import binary_metrics, select_threshold


def fingerprint(value):
    return sha256(json.dumps(value, sort_keys=True).encode()).hexdigest()


def evaluate(output, cases_per_segment=8):
    from detector import GraphDetector
    from graph_models import Transaction
    from financial import assess_financial

    detector = GraphDetector([])
    splits = {"validation": generate_split("validation", 104729, cases_per_segment),
              "test": generate_split("test", 982451653, cases_per_segment)}
    outputs = {}
    for split, cases in splits.items():
        records = []
        for case in cases:
            assessment = assess_financial(detector,
                [Transaction.model_validate(tx) for tx in case["transactions"]],
                [Transaction.model_validate(tx) for tx in case["baseline_transactions"]])
            records.append({"sample_id": case["sample_id"], "label": case["label"], "segment": case["segment"],
                            "rules": max(score.detectors.rules for score in assessment.transaction_scores),
                            "raw_tgnn": max(score.raw_ml_score for score in assessment.transaction_scores),
                            "fused": assessment.risk_score})
        outputs[split] = records
    models = {}
    for name in ["rules", "raw_tgnn", "fused"]:
        validation, test = outputs["validation"], outputs["test"]
        threshold = select_threshold([r["label"] for r in validation], [r[name] for r in validation])
        models[name] = {
            "threshold_selected_on_validation": threshold,
            "selection_target_maximum_false_positive_rate": 0.05,
            "held_out_at_selected_threshold": binary_metrics([r["label"] for r in test], [r[name] for r in test], threshold),
            "held_out_at_current_policy_threshold": binary_metrics([r["label"] for r in test], [r[name] for r in test], 0.70),
            "segments_at_current_policy_threshold": {segment: binary_metrics(
                [r["label"] for r in test if r["segment"] == segment],
                [r[name] for r in test if r["segment"] == segment], 0.70)
                for segment in ["normal", "mule", "scam", "payroll_control"]},
        }
    report = {
        "schema_version": "synthetic-evaluation.v1",
        "scope": "Engineering evaluation only; no real-data or production accuracy claim",
        "data_provenance": "Locally generated synthetic data, no third-party customer dataset",
        "licence_note": "Generated by repository code; no external dataset licence is relied on. Real-data licence approval remains pending.",
        "training_data": "Existing bundled synthetic normal/attack batches; checkpoint not retrained or tuned on these splits",
        "training_fingerprint": fingerprint({name: json.loads((ROOT / f"data/{name}/transactions.json").read_text()) for name in ["normal", "attack"]}),
        "model_checkpoint_sha256": sha256((ROOT / "services/graph-detector/tgnn_weights.pt").read_bytes()).hexdigest(),
        "dataset_fingerprints": {split: fingerprint(cases) for split, cases in splits.items()},
        "split_policy": "Distinct customer namespaces, fixed independent seeds, validation date before test; thresholds frozen before test scoring metrics",
        "seeds": {"validation": 104729, "test": 982451653},
        "development_note": "Earlier synthetic seed 130363 exposed payroll false positives and was used for policy development; final test seed was changed after that correction.",
        "source_fingerprints": {name: sha256((ROOT / name).read_text(encoding="utf-8").replace("\r\n", "\n").encode()).hexdigest() for name in [
            "services/graph-detector/financial.py", "services/graph-detector/tgnn.py",
            "services/graph-detector/detector.py", "services/graph-detector/features.py",
            "services/graph-detector/graph_builder.py", "services/graph-detector/mule_detector.py",
            "services/graph-detector/scam_detector.py", "services/graph-detector/history.py",
            "contracts/financial_models.py", "evaluation/dataset.py", "evaluation/metrics.py"]},
        "threshold_note": "A threshold above 1 disables detection when validation cannot meet the FPR target. This report does not change deployed policy.",
        "metrics": models, "samples": outputs,
        "remaining_work": ["Approved representative labelled data", "Training/validation/test lineage and independent real-data evaluation",
                           "Payroll/scam distinction and threshold calibration", "Validated ML feature attribution"],
    }
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({name: values["held_out_at_current_policy_threshold"] for name, values in models.items()}, indent=2))
    print(f"Synthetic evaluation report: {output}")
    return report


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "reports/financial-evaluation.json")
    parser.add_argument("--cases-per-segment", type=int, default=8)
    args = parser.parse_args()
    if not 1 <= args.cases_per_segment <= 100:
        parser.error("cases-per-segment must be between 1 and 100")
    evaluate(args.output, args.cases_per_segment)
